// "כובע. מטרייה. או כפפות": one short sentence per option, so each can be
// recorded once and reused.
export function listWords(words) {
  return words.map((word, i) => (i === words.length - 1 ? `או ${word}` : word)).join('. ');
}

// "the fish" for "fish": ה on the first word, or on the second word of a
// construct pair (דוב קוטב -> דוב הקוטב).
function definite(name) {
  const words = name.split(' ');
  if (words.length === 2) return `${words[0]} ה${words[1]}`;
  return `ה${name}`;
}

